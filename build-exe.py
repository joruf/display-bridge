#!/usr/bin/env python3
"""Build the DisplayBridge programs as single executable files.

One command, the same on every platform - run it on the system the files are
meant for, because PyInstaller cannot build for another one:

    ./build-exe.py              Linux   -> dist/display-bridge-<program>-linux-x86_64-<version>-build<build>
    py build-exe.py             Windows -> dist/display-bridge-<program>-windows-x86_64-<version>-build<build>.exe

DisplayBridge is two programs, so there are two files per platform:
``display-bridge-sender`` (python/displayBridgeSender.py) and
``display-bridge-receiver`` (python/displayBridgeReceiver.py).  The browser
versions in ``webui/`` are not part of this build.

What it does:

1. creates a private build environment in ``build/exe/venv`` (without the
   system's site packages, so nothing the build machine happens to have ends up
   in the files),
2. installs PyInstaller and the libraries the programs need: OpenCV (the
   headless wheel - the programs only capture and write video, they never open
   an OpenCV window), NumPy, Pillow, qrcode, pyzbar and tkinterdnd2,
3. writes a runtime hook and the PyInstaller spec for each program,
4. runs PyInstaller and starts each result with ``--version``, which also
   imports every library the program needs.

Linux needs the ZBar library on the build machine (``sudo apt install
libzbar0``); PyInstaller packs it, so the file runs without it.  The Windows
pyzbar wheel carries its own DLLs.

The version is derived from the git history, like in the other projects:

    major.minor  set by hand below
    patch        number of commits that touched ``python/``
    build        number of all commits

The history is needed, so build from a full clone (the workflow checks out
everything).  ``DISPLAY_BRIDGE_VERSION="1.0.2 30"`` replaces the derivation.

Options:

    --clean          rebuild the build environment from scratch
    --keep-env       reuse the build environment without updating its packages
    --print-version  print "<version> <build>" and exit (used by the workflow)

Author:  Joachim Ruf, Loresoft.de
"""

from __future__ import annotations

import argparse
import os
import platform
import shutil
import subprocess
import sys
import venv
from pathlib import Path
from typing import List, Tuple

ROOT = Path(__file__).resolve().parent

APP_ID = "display-bridge"
IS_WINDOWS = sys.platform.startswith("win")
IS_LINUX = sys.platform.startswith("linux")

#: Raised by hand, and only for a release that genuinely justifies it.
MAJOR = 1
MINOR = 0
VERSION_VARIABLE = "DISPLAY_BRIDGE_VERSION"

BUILD_DIR = ROOT / "build" / "exe"
VENV_DIR = BUILD_DIR / "venv"
WORK_DIR = BUILD_DIR / "work"
DIST_DIR = ROOT / "dist"

#: The same PyInstaller generation the other projects build with.
PYINSTALLER_SPEC = "pyinstaller>=6.9"

#: What the programs import, as pip names.  The programs install these themselves
#: when they run from source; a single file cannot, so they are built in.
LIBRARIES = [
    "opencv-python-headless",
    "numpy",
    "pillow",
    "qrcode[pil]",
    "pyzbar",
    "tkinterdnd2-universal",
]

#: The programs: key -> (title, script, modules that must import, optional modules).
PROGRAMS = {
    "sender": {
        "title": "DisplayBridge Sender",
        "script": Path("python") / "displayBridgeSender.py",
        "required": ["tkinter", "cv2", "numpy", "PIL.ImageTk", "qrcode", "tkinterdnd2"],
    },
    "receiver": {
        "title": "DisplayBridge Receiver",
        "script": Path("python") / "displayBridgeReceiver.py",
        "required": ["tkinter", "cv2", "numpy", "PIL.ImageTk", "pyzbar.pyzbar"],
    },
}

#: Third-party packages whose submodules and data files are collected completely.
COLLECT_ALL = ["tkinterdnd2", "pyzbar", "qrcode"]

HOOK_TEMPLATE = '''# Generated by build-exe.py - edit that script, not this file.
"""Runs before {script}, inside the single-file executable.

* gives child programs the library path of the system (Linux),
* stops with a readable message when a library is missing: the program would
  otherwise try to ``pip install`` it by starting ``sys.executable``, which is this
  very file, and start itself over and over,
* answers ``--version`` after importing everything the program needs, so the start
  test of the build proves the libraries load.
"""
import os
import sys

TITLE = {title!r}
VERSION = {version!r}
REQUIRED = {required!r}


def _fail(text):
    try:
        sys.stderr.write(text + "\\n")
    except Exception:
        pass
    if "--version" not in sys.argv:
        try:
            import tkinter
            from tkinter import messagebox

            root = tkinter.Tk()
            root.withdraw()
            messagebox.showerror(TITLE, text)
        except Exception:
            pass
    sys.exit(1)


if getattr(sys, "frozen", False) and sys.platform.startswith("linux"):
    # PyInstaller points LD_LIBRARY_PATH at the unpacked files; a child program that
    # inherits it loads the bundled libraries instead of its own.
    original = os.environ.get("LD_LIBRARY_PATH_ORIG")
    if original is None:
        os.environ.pop("LD_LIBRARY_PATH", None)
    else:
        os.environ["LD_LIBRARY_PATH"] = original

for module in REQUIRED:
    try:
        __import__(module)
    except Exception as error:
        _fail("{{0}} cannot start: the library {{1}} could not be loaded ({{2}}).".format(TITLE, module, error))

if sys.argv[1:] == ["--version"]:
    print("{{0}} {{1}}".format(TITLE, VERSION))
    sys.exit(0)
'''

SPEC_TEMPLATE = '''# Generated by build-exe.py - edit that script, not this file.
from PyInstaller.utils.hooks import collect_all

datas = []
binaries = []
hiddenimports = {hidden!r}
for package in {collect!r}:
    package_datas, package_binaries, package_imports = collect_all(package)
    datas += package_datas
    binaries += package_binaries
    hiddenimports += package_imports

a = Analysis(
    [{entry!r}],
    pathex=[{python!r}],
    binaries=binaries,
    datas=datas,
    hiddenimports=hiddenimports,
    hookspath=[],
    hooksconfig={{}},
    runtime_hooks=[{hook!r}],
    excludes=[],
    noarchive=False,
)
pyz = PYZ(a.pure)
exe = EXE(
    pyz,
    a.scripts,
    a.binaries,
    a.datas,
    [],
    name={name!r},
    debug=False,
    strip=False,
    upx=False,
    runtime_tmpdir=None,
    # A desktop program: no console window on Windows.
    console=False,
    icon=None,
)
'''


def info(message: str) -> None:
    """Print a progress line."""
    print("[build-exe] " + message, flush=True)


def fail(message: str) -> None:
    """Print an error and stop with exit code 1."""
    print("[build-exe] ERROR: " + message, file=sys.stderr, flush=True)
    sys.exit(1)


def _git(*args: str) -> str:
    """Run one read-only git command in the project folder; empty on any failure."""
    git = shutil.which("git")
    if git is None:
        return ""
    try:
        done = subprocess.run([git, "-C", str(ROOT), *args], stdout=subprocess.PIPE,
                              stderr=subprocess.DEVNULL, timeout=30, check=False)
    except (OSError, subprocess.SubprocessError):
        return ""
    return done.stdout.decode("utf-8", errors="replace").strip() if done.returncode == 0 else ""


def parse_version(text: str) -> Tuple[str, str]:
    """Split ``"<version> <build>"`` into its two parts."""
    parts = text.split()
    if len(parts) != 2 or not parts[1].isdigit() or parts[0].count(".") != 2:
        fail("{0} must look like '1.0.2 30', got {1!r}".format(VERSION_VARIABLE, text))
    return parts[0], parts[1]


def build_version() -> Tuple[str, str]:
    """Return ``(version, build)``, from the environment or from the git history."""
    fixed = os.environ.get(VERSION_VARIABLE, "").strip()
    if fixed:
        return parse_version(fixed)
    total = _git("rev-list", "--count", "HEAD")
    program = _git("rev-list", "--count", "HEAD", "--", "python")
    if not total.isdigit() or not program.isdigit() or int(total) == 0:
        fail("no version: this is not a git clone with history (set {0}='1.0.2 30' to build anyway).".format(
            VERSION_VARIABLE))
    if _git("rev-parse", "--is-shallow-repository") == "true":
        fail("this is a shallow clone, so the commit count is wrong - fetch the full history "
             "(git fetch --unshallow).")
    return "{0}.{1}.{2}".format(MAJOR, MINOR, program), total


def executable_name(program: str, version: str, build: object) -> str:
    """Return the file name of one program's executable on this platform.

    :param program: ``sender`` or ``receiver``.
    :param version: ``major.minor.patch``.
    :param build: The build number.
    :return: e.g. ``display-bridge-sender-linux-x86_64-1.0.2-build30`` or
        ``display-bridge-receiver-windows-x86_64-1.0.2-build30.exe``.
    """
    machine = platform.machine().lower()
    machine = {"amd64": "x86_64", "x64": "x86_64", "arm64": "aarch64"}.get(machine, machine)
    system = "windows" if IS_WINDOWS else "linux"
    return "{0}-{1}-{2}-{3}-{4}-build{5}{6}".format(
        APP_ID, program, system, machine, version, build, ".exe" if IS_WINDOWS else "")


def venv_python() -> Path:
    """Return the interpreter of the build environment."""
    if IS_WINDOWS:
        return VENV_DIR / "Scripts" / "python.exe"
    return VENV_DIR / "bin" / "python"


def run(command: List[object], **kwargs) -> None:
    """Run a command and stop the build when it fails."""
    info("$ " + " ".join(str(part) for part in command))
    completed = subprocess.run([str(part) for part in command], **kwargs)
    if completed.returncode != 0:
        fail("command failed with exit code {0}".format(completed.returncode))


def check_build_host() -> None:
    """Stop early when this machine cannot produce a complete program."""
    if not (IS_LINUX or IS_WINDOWS):
        fail("DisplayBridge runs on Linux and Windows; build on one of them.")
    if sys.version_info < (3, 10):
        fail("building needs Python 3.10 or newer.")
    try:
        import tkinter  # noqa: F401
    except ImportError:
        fail("tkinter is missing - Linux: sudo apt install python3-tk")
    if IS_LINUX and not _zbar_found():
        fail("the ZBar library is missing - Linux: sudo apt install libzbar0")


def _zbar_found() -> bool:
    """Return ``True`` when the system has ZBar, which PyInstaller packs on Linux."""
    from ctypes.util import find_library

    return find_library("zbar") is not None


def prepare_venv(clean: bool, keep: bool) -> None:
    """Create or refresh the build environment."""
    if clean and VENV_DIR.exists():
        info("Removing the old build environment ...")
        shutil.rmtree(str(VENV_DIR))
    if not venv_python().exists():
        info("Creating the build environment in {0} ...".format(VENV_DIR))
        venv.EnvBuilder(with_pip=True).create(str(VENV_DIR))
    elif keep:
        info("Reusing the build environment as it is.")
        return
    run([venv_python(), "-m", "pip", "install", "--upgrade", "--disable-pip-version-check", "pip"])
    run([venv_python(), "-m", "pip", "install", "--upgrade", "--disable-pip-version-check",
         PYINSTALLER_SPEC] + LIBRARIES)


def hook_text(program: str, version: str, build: str) -> str:
    """Return the runtime hook of one program."""
    settings = PROGRAMS[program]
    return HOOK_TEMPLATE.format(
        script=settings["script"].name,
        title=settings["title"],
        version="{0} ({1})".format(version, build),
        required=settings["required"],
    )


def spec_text(program: str, version: str, build: str) -> str:
    """Return the PyInstaller spec file of one program for this platform."""
    settings = PROGRAMS[program]
    return SPEC_TEMPLATE.format(
        hidden=["PIL._tkinter_finder", "PIL.ImageTk"],
        collect=COLLECT_ALL,
        entry=str(ROOT / settings["script"]),
        python=str(ROOT / "python"),
        hook=str(WORK_DIR / "hook-{0}.py".format(program)),
        name=executable_name(program, version, build)[: -len(".exe")] if IS_WINDOWS
        else executable_name(program, version, build),
    )


def smoke_test(executable: Path, expected: str) -> None:
    """Start the result once and make sure it answers."""
    info("Starting {0} --version ...".format(executable.name))
    completed = subprocess.run([str(executable), "--version"], stdout=subprocess.PIPE,
                               stderr=subprocess.STDOUT, timeout=300)
    output = completed.stdout.decode("utf-8", errors="replace").strip()
    if completed.returncode != 0:
        fail("the executable did not start (exit code {0}):\n{1}".format(completed.returncode, output))
    # A windowed Windows build has no stdout to print to; the exit code has to do.
    if output and expected not in output:
        fail("the executable reports {0!r}, expected {1}".format(output, expected))
    info("OK: " + (output or "exit code 0"))


def build_program(program: str, version: str, build: str) -> Path:
    """Build and test one program; return its file."""
    WORK_DIR.mkdir(parents=True, exist_ok=True)
    (WORK_DIR / "hook-{0}.py".format(program)).write_text(hook_text(program, version, build), encoding="utf-8")
    spec = WORK_DIR / "{0}.spec".format(program)
    spec.write_text(spec_text(program, version, build), encoding="utf-8")
    run([venv_python(), "-m", "PyInstaller", "--noconfirm", "--clean",
         "--distpath", DIST_DIR, "--workpath", WORK_DIR / program, spec], cwd=str(ROOT))
    result = DIST_DIR / executable_name(program, version, build)
    if not result.is_file():
        fail("PyInstaller finished but {0} is missing".format(result))
    smoke_test(result, "{0} ({1})".format(version, build))
    info("Done: {0} ({1:.1f} MB)".format(result, result.stat().st_size / 1048576))
    return result


def main() -> int:
    """Run the whole build."""
    parser = argparse.ArgumentParser(description="Build the DisplayBridge programs as single executable files.")
    parser.add_argument("--clean", action="store_true", help="rebuild the build environment from scratch")
    parser.add_argument("--keep-env", action="store_true",
                        help="reuse the build environment without updating its packages")
    parser.add_argument("--print-version", action="store_true",
                        help='print "<version> <build>" and exit')
    args = parser.parse_args()

    version, build = build_version()
    if args.print_version:
        print("{0} {1}".format(version, build))
        return 0

    check_build_host()
    info("DisplayBridge {0} ({1}) for {2}".format(version, build, "Windows" if IS_WINDOWS else "Linux"))
    prepare_venv(clean=args.clean, keep=args.keep_env)
    for program in PROGRAMS:
        build_program(program, version, build)
    info("These files run on {0} only; build on the other system for its own files.".format(
        "Windows" if IS_WINDOWS else "Linux (the same or a newer glibc than this machine)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
